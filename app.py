import sys
import os
import json
import joblib
import pandas as pd
from flask import Flask, render_template, request

# Compatibility patch for unpickling gradient boosting models across sklearn versions
try:
    import sklearn._loss._loss
    sys.modules['_loss'] = sklearn._loss._loss
except (ImportError, AttributeError):
    pass

app = Flask(__name__)
ROOT = os.path.dirname(os.path.abspath(__file__))

# Load metadata
with open(os.path.join(ROOT, "metadata.json"), encoding="utf-8") as f:
    META = json.load(f)

# Extract available districts from metadata.json
if "districts_by_state" in META:
    districts = sorted({d for dist_list in META["districts_by_state"].values() for d in dist_list})
else:
    districts = []

# Load automatic weather lookup table
WEATHER_PATH = os.path.join(ROOT, "state_year_weather_lookup.csv")
if os.path.exists(WEATHER_PATH):
    WEATHER = pd.read_csv(WEATHER_PATH)
    WEATHER["State_Name"] = WEATHER["State_Name"].astype(str).str.strip().str.title()
    WEATHER["Crop_Year"] = pd.to_numeric(WEATHER["Crop_Year"], errors="coerce")
else:
    WEATHER = pd.DataFrame(columns=["State_Name", "Crop_Year"] + META.get("weather_features", []))

# Load all trained pipeline models using robust absolute paths
MODELS = {
    "Random Forest": joblib.load(os.path.join(ROOT, "models", "random_forest.joblib")),
    "XGBoost": joblib.load(os.path.join(ROOT, "models", "xgboost.joblib")),
    "Gradient Boosting": joblib.load(os.path.join(ROOT, "models", "gradient_boosting.joblib")),
}

# Load evaluation metrics generated by training
comparison_rows = []
comparison_path = os.path.join(ROOT, "model_comparison.csv")
if not os.path.exists(comparison_path):
    comparison_path = os.path.join(ROOT, "model_evaluation_results.csv")

if os.path.exists(comparison_path):
    try:
        comparison_df = pd.read_csv(comparison_path)
        for _, row in comparison_df.iterrows():
            comparison_rows.append({
                "model": str(row["model"]).replace("_", " ").title(),
                "mae": float(row["MAE"]),
                "rmse": float(row["RMSE"]),
                "r2": float(row["R2"]),
            })
    except (ValueError, KeyError, TypeError):
        comparison_rows = []

# Model selection logic: prioritize highest R², then lower RMSE, then lower MAE
MODEL_NAME_MAP = {
    "gradient boosting": "Gradient Boosting",
    "xgboost": "XGBoost",
    "random forest": "Random Forest",
}
meta_best_key = str(META.get("best_model", "xgboost")).lower().replace("_", " ")
selected_model = MODEL_NAME_MAP.get(meta_best_key, "XGBoost")


@app.route("/", methods=["GET", "POST"])
def index():
    result = None
    error = None
    form = {
        "state": "",
        "district": "",
        "crop": "Rice",
        "season": "Kharif",
        "year": "2022",
        "area": "1",
    }

    if request.method == "POST":
        form = {key: request.form.get(key, "") for key in form}
        try:
            state = form["state"]
            district = form["district"]
            crop = form["crop"]
            season = form["season"]
            year = int(form["year"])
            area = float(form["area"])

            if state not in META["states"]:
                raise ValueError("Please select a valid state.")

            districts_for_state = META.get("districts_by_state", {}).get(state, districts)
            if district and districts_for_state and district not in districts_for_state:
                raise ValueError("Please select a valid district for the selected state.")

            if crop not in META["crops"]:
                raise ValueError("Please select a valid crop from the list.")
            if season not in META["seasons"]:
                raise ValueError("Please select a valid season.")
            if area <= 0:
                raise ValueError("Area must be greater than zero.")
            if year < 1960 or year > 2035:
                raise ValueError("Enter a year between 1960 and 2035.")

            # Automatic weather lookup:
            # Query state_year_weather_lookup for historical weather features
            state_norm = str(state).strip().title()
            match = WEATHER[
                (WEATHER["State_Name"] == state_norm) &
                (WEATHER["Crop_Year"] == year)
            ]
            weather_found = not match.empty
            weather_dict = {}
            for col in META["weather_features"]:
                val = match.iloc[0][col] if weather_found and pd.notna(match.iloc[0][col]) else float("nan")
                weather_dict[col] = float(val)

            # Construct feature row according to trained pipeline schema
            row = {
                "State_Name": state_norm,
                "Crop": str(crop).strip().title(),
                "Season": str(season).strip().title(),
                "Crop_Year": year,
                "Area": area,
                **weather_dict
            }
            X = pd.DataFrame([row], columns=META["feature_columns"])

            # Compute predictions across all trained models
            predictions = {
                name: max(0.0, float(model.predict(X)[0]))
                for name, model in MODELS.items()
            }

            # Optional weather highlights for UI display
            weather_summary = None
            if weather_found:
                weather_summary = {
                    "avg_max_temp": round(weather_dict["temp_avg_maximum_temperature"], 1) if pd.notna(weather_dict.get("temp_avg_maximum_temperature")) else None,
                    "avg_min_temp": round(weather_dict["temp_avg_minimum_temperature"], 1) if pd.notna(weather_dict.get("temp_avg_minimum_temperature")) else None,
                    "rainfall_annual": round(weather_dict["rainfall_actual_year_sum"], 1) if pd.notna(weather_dict.get("rainfall_actual_year_sum")) else None,
                }

            result = {
                "predictions": predictions,
                "selected": selected_model,
                "yield": predictions[selected_model],
                "production": predictions[selected_model] * area,
                "area": area,
                "weather_found": weather_found,
                "weather_summary": weather_summary,
            }
        except Exception as exc:
            error = str(exc)

    if form["state"]:
        visible_districts = META.get("districts_by_state", {}).get(form["state"], districts)
    else:
        visible_districts = districts

    return render_template(
        "index.html",
        meta=META,
        districts=visible_districts,
        form=form,
        result=result,
        error=error,
        comparison_rows=comparison_rows,
        selected_model=selected_model,
    )


if __name__ == "__main__":
    app.run(debug=True)
